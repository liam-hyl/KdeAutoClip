#!/usr/bin/env bash
# Bootstrap a self-contained toolchain for building the KdeAutoClip LSPosed module.
#
# Downloads (into ../.toolchain, ~350 MB):
#   - JDK 17            (Adoptium, fallback: Amazon Corretto / Microsoft OpenJDK)
#   - Android build-tools r35   (aapt2, d8, zipalign, apksigner)
#   - Android platform 36       (android.jar for API 36 = Android 16)
#   - Xposed legacy API 82 jar  (compile-only)
#
# Proxy: plain curl env vars (https_proxy / http_proxy) are honoured automatically.
# Usage:  bash tools/bootstrap.sh
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
TOOL="$ROOT/.toolchain"
DL="$TOOL/downloads"
mkdir -p "$TOOL" "$DL"

CURL=(curl -fL --retry 3 --retry-delay 2 --connect-timeout 25)

log() { printf '==> %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- JDK 17
JDK_HOME=""
if [ -x "$TOOL/jdk/bin/javac" ]; then
  JDK_HOME="$TOOL/jdk"
fi
if [ -z "$JDK_HOME" ]; then
  log "downloading JDK 17"
  urls=(
    # fast Chinese mirrors of the same Adoptium build first
    "https://mirrors.tuna.tsinghua.edu.cn/Adoptium/17/jdk/x64/linux/OpenJDK17U-jdk_x64_linux_hotspot_17.0.21.1_2.tar.gz"
    "https://api.adoptium.net/v3/binary/latest/17/ga/linux/x64/jdk/hotspot/normal/eclipse"
    "https://corretto.aws/downloads/latest/amazon-corretto-17-x64-linux-jdk.tar.gz"
    "https://aka.ms/download-jdk/microsoft-jdk-17-linux-x64.tar.gz"
  )
  ok=0
  for u in "${urls[@]}"; do
    printf '    trying %s\n' "$u"
    if "${CURL[@]}" --max-time 900 -o "$DL/jdk.tar.gz" "$u" && [ -s "$DL/jdk.tar.gz" ]; then
      ok=1; break
    fi
    rm -f "$DL/jdk.tar.gz"
  done
  [ "$ok" = 1 ] || die "could not download a JDK 17 tarball"
  rm -rf "$TOOL/jdk"
  mkdir -p "$TOOL/jdk"
  tar -xzf "$DL/jdk.tar.gz" -C "$TOOL/jdk" --strip-components=1
  [ -x "$TOOL/jdk/bin/javac" ] || die "JDK tarball did not contain bin/javac"
  JDK_HOME="$TOOL/jdk"
fi

# ------------------------------------------------- Android build-tools r35
if [ ! -x "$TOOL/build-tools/aapt2" ]; then
  log "downloading Android build-tools r35"
  urls=(
    "https://mirrors.cloud.tencent.com/AndroidSDK/build-tools_r35_linux.zip"
    "https://dl.google.com/android/repository/build-tools_r35_linux.zip"
  )
  ok=0
  for u in "${urls[@]}"; do
    if "${CURL[@]}" --max-time 900 -o "$DL/build-tools.zip" "$u" && [ -s "$DL/build-tools.zip" ]; then ok=1; break; fi
    rm -f "$DL/build-tools.zip"
  done
  [ "$ok" = 1 ] || die "build-tools download failed"
  rm -rf "$TOOL/build-tools-raw" "$TOOL/build-tools"
  mkdir -p "$TOOL/build-tools-raw"
  python3 -m zipfile -e "$DL/build-tools.zip" "$TOOL/build-tools-raw"
  aapt2_path="$(find "$TOOL/build-tools-raw" -type f -name aapt2 | head -1)"
  [ -n "$aapt2_path" ] || die "aapt2 not found inside build-tools zip"
  mv "$(dirname "$aapt2_path")" "$TOOL/build-tools"
  rm -rf "$TOOL/build-tools-raw"
  # python's zipfile extraction drops the executable bit
  find "$TOOL/build-tools" -maxdepth 1 -type f -exec chmod +x {} +
fi

# ------------------------------------------------- Android platform (API 36)
if [ ! -s "$TOOL/android.jar" ]; then
  log "downloading Android platform 36 (android.jar)"
  urls=(
    "https://mirrors.cloud.tencent.com/AndroidSDK/platform-36_r01.zip"
    "https://dl.google.com/android/repository/platform-36_r01.zip"
  )
  ok=0
  for u in "${urls[@]}"; do
    if "${CURL[@]}" --max-time 900 -o "$DL/platform.zip" "$u" && [ -s "$DL/platform.zip" ]; then ok=1; break; fi
    rm -f "$DL/platform.zip"
  done
  [ "$ok" = 1 ] || die "platform download failed"
  rm -rf "$TOOL/platform-raw"
  mkdir -p "$TOOL/platform-raw"
  python3 -m zipfile -e "$DL/platform.zip" "$TOOL/platform-raw"
  jar_path="$(find "$TOOL/platform-raw" -type f -name android.jar | head -1)"
  [ -n "$jar_path" ] || die "android.jar not found inside platform zip"
  cp "$jar_path" "$TOOL/android.jar"
  rm -rf "$TOOL/platform-raw"
fi

# ------------------------------------------------- Xposed legacy API 82 jar
if [ ! -s "$TOOL/api-82.jar" ]; then
  log "downloading Xposed API 82 jar"
  urls=(
    "https://mirrors.huaweicloud.com/repository/maven/de/robv/android/xposed/api/82/api-82.jar"
    "https://maven.aliyun.com/repository/jcenter/de/robv/android/xposed/api/82/api-82.jar"
    "https://raw.githubusercontent.com/fei-ke/ClipboardWhitelist/master/app/compile-libs/XposedBridgeApi-82.jar"
  )
  ok=0
  for u in "${urls[@]}"; do
    if "${CURL[@]}" --max-time 120 -o "$TOOL/api-82.jar" "$u"; then
      sz="$(wc -c < "$TOOL/api-82.jar")"
      if [ "$sz" -gt 5000 ]; then ok=1; break; fi
    fi
    rm -f "$TOOL/api-82.jar"
  done
  [ "$ok" = 1 ] || die "could not download Xposed API 82 jar"
fi

# ------------------------------------------------- write env file
cat > "$TOOL/env.sh" <<EOF
# generated by tools/bootstrap.sh
export JAVA_HOME="$JDK_HOME"
export PATH="$JDK_HOME/bin:\$PATH"
export ANDROID_JAR="$TOOL/android.jar"
export BUILD_TOOLS="$TOOL/build-tools"
export XPOSED_API_JAR="$TOOL/api-82.jar"
EOF
chmod +x "$TOOL/env.sh"

log "toolchain ready in $TOOL"
# shellcheck disable=SC1090
. "$TOOL/env.sh"
"$JAVA_HOME/bin/java" -version
"$BUILD_TOOLS/aapt2" version
"$JAVA_HOME/bin/javac" -version
printf '    android.jar: %s\n' "$ANDROID_JAR"
printf '    api-82.jar : %s\n' "$XPOSED_API_JAR"
